import math
a = float(input("Введите длину стороны основания (a): "))
h = float(input("Введите высоту призмы (h): "))
if a <= 0 or h <= 0:
    print("\nОшибка: длина стороны основания и высота призмы должны быть больше нуля!")
else:
    #Площадь одного основания
    s_base = (3 * math.sqrt(3) / 2) * math.pow(a, 2)
    #Объем призмы
    v = s_base * h
    #Площадь боковой поверхности
    s_side = 6 * a * h
    #Площадь полной поверхности
    s_full = s_side + 2 * s_base
    # Вывод результатов с 2 знаками после запятой
    print("\n--- Результаты расчетов ---")
    print("Площадь основания: {0:.2f}".format(s_base))
    print("Объем призмы (V): {0:.2f}".format(v))
    print("Площадь боковой поверхности: {0:.2f}".format(s_side))
    print("Площадь полной поверхности: {0:.2f}".format(s_full))
